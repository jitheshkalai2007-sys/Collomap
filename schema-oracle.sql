CREATE TABLE Students (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL,
    marks10 NUMBER(5,2) NOT NULL CHECK (marks10 BETWEEN 0 AND 100),
    marks12 NUMBER(5,2) NOT NULL CHECK (marks12 BETWEEN 0 AND 100),
    preferredCourse VARCHAR2(150) NOT NULL
);

CREATE TABLE Courses (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(150) NOT NULL UNIQUE
);

CREATE TABLE Colleges (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(200) NOT NULL,
    type VARCHAR2(20) NOT NULL CHECK (type IN ('GOVERNMENT', 'PRIVATE')),
    location VARCHAR2(500) NOT NULL,
    rating NUMBER(3,2) NOT NULL CHECK (rating BETWEEN 0 AND 5),
    infra NUMBER(5,2) NOT NULL CHECK (infra BETWEEN 0 AND 100),
    food NUMBER(5,2) NOT NULL CHECK (food BETWEEN 0 AND 100),
    transport NUMBER(5,2) NOT NULL CHECK (transport BETWEEN 0 AND 100)
);

CREATE TABLE Cutoffs (
    college_id NUMBER NOT NULL REFERENCES Colleges(id),
    course_id NUMBER NOT NULL REFERENCES Courses(id),
    cutoff NUMBER(5,2) NOT NULL CHECK (cutoff BETWEEN 0 AND 100),
    PRIMARY KEY (college_id, course_id)
);

CREATE TABLE Contacts (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id NUMBER NOT NULL REFERENCES Colleges(id),
    staff_name VARCHAR2(150) NOT NULL,
    designation VARCHAR2(150) NOT NULL,
    phone_number VARCHAR2(40) NOT NULL
);
